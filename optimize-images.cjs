// npm install, then node optimize-images.cjs. Source photos and icon PNGs are kept.
const sharp = require(process.argv[2] || 'sharp');
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const folder = path.join(root,'assets/img');
const output = path.join(folder,'optimized');
(async()=>{
  fs.mkdirSync(output,{recursive:true});
  const manifest={};let before=0,after=0;
  for(const file of fs.readdirSync(folder).filter(f=>/\.(png|jpe?g|webp)$/i.test(f))) {
    const source=path.join(folder,file),target=path.join(output,file+'.webp');
    const image=sharp(source).rotate();
    const info=await image.resize({width:2560,height:2560,fit:'inside',withoutEnlargement:true}).webp({quality:90,effort:5,smartSubsample:true}).toFile(target);
    before+=fs.statSync(source).size;after+=info.size;
    manifest[file]={file:'optimized/'+file+'.webp',width:info.width,height:info.height};
  }
  fs.writeFileSync(path.join(folder,'image-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  fs.writeFileSync(path.join(root,'assets/js/images.js'),`// Generated by optimize-images.cjs. Original database filenames stay unchanged.\n(() => {\n  const images = ${JSON.stringify(manifest)};\n  window.HotelImages = {\n    url(filename, base) {\n      const safe = /^[a-z0-9][a-z0-9._-]*\\.(png|jpe?g|webp|avif)$/i.test(filename || '');\n      const name = safe ? filename : 'hero.png';\n      return new URL('assets/img/' + (images[name]?.file || name), base).href;\n    }\n  };\n})();\n`);
  console.log(`Photos: ${(before/1048576).toFixed(1)} MiB → ${(after/1048576).toFixed(1)} MiB (${Object.keys(manifest).length} photos). Original icons unchanged.`);
})().catch(error=>{console.error(error);process.exitCode=1;});

// Run: node build-sprite.cjs. No dependencies; originals stay in assets/img/icons.
// PNG bytes are embedded unchanged. Polygon backgrounds remain vector artwork.
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const icons = [['down','down.png'],['up','up.png'],['right','right.png'],
  ['star','Star.png'],['star-large','Starbig.png'],['flower','flower.png']];
const gap = 8;
let x = gap, tallest = 0;
const entries = icons.map(([name,file]) => {
  const bytes = fs.readFileSync(path.join(root,'assets/img/icons',file));
  const width = bytes.readUInt32BE(16), height = bytes.readUInt32BE(20);
  const entry = {name,file,x,y:gap,width,height,
    artwork:`<image x="${x}" y="${gap}" width="${width}" height="${height}" href="data:image/png;base64,${bytes.toString('base64')}"/>`};
  x += width + gap * 2; tallest = Math.max(tallest,height);
  return entry;
});
const decagon = '50,5 76.45,13.59 92.79,36.08 92.79,63.92 76.45,86.41 50,95 23.55,86.41 7.21,63.92 7.21,36.08 23.55,13.59';
const polygons = [
  ['octagon-outline','30,5 70,5 95,30 95,70 70,95 30,95 5,70 5,30',false],
  ['decagon-outline',decagon,false],
  ['decagon-gold',decagon,true]
];
polygons.forEach(([name,points,filled],index) => {
  const px = gap + index * (100 + gap * 2), py = tallest + gap * 3;
  entries.push({name,x:px,y:py,width:100,height:100,
    artwork:`<g transform="translate(${px} ${py})"><polygon points="${points}" ${filled ? 'fill="#fcd043"' : 'fill="none" stroke="#fffcf6" stroke-opacity=".35" stroke-width=".5"'}/></g>`});
});
const width = x, height = tallest + gap * 4 + 100;
fs.writeFileSync(path.join(root,'assets/img/icons/sprite.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" preserveAspectRatio="none">\n${entries.map(e=>e.artwork).join('\n')}\n</svg>\n`);
const number = n => Number(n.toFixed(10));
let css = `/* Generated by node build-sprite.cjs. Set --icon-size to change display width. */
.sprite {
  --icon-size: 28px;
  --icon-height: calc(var(--icon-size) * var(--sprite-ratio));
  display: inline-block;
  flex-shrink: 0;
  width: var(--icon-size);
  height: var(--icon-height);
  vertical-align: middle;
  background-image: url('../img/icons/sprite.svg');
  background-repeat: no-repeat;
  background-size: calc(var(--icon-size) * var(--sheet-width)) calc(var(--icon-height) * var(--sheet-height));
  background-position: calc(var(--icon-size) * var(--sprite-x)) calc(var(--icon-height) * var(--sprite-y));
  pointer-events: none;
}
/* Square backgrounds scale with the existing polygon button dimensions. */
.sprite.polygon {
  --icon-size: 100%;
  height: 100%;
  background-size: ${width}% ${height}%;
  background-position: var(--polygon-x) var(--polygon-y);
}
`;
for (const e of entries) {
  css += `.sprite-${e.name} { --sprite-ratio: ${number(e.height/e.width)}; --sheet-width: ${number(width/e.width)}; --sheet-height: ${number(height/e.height)}; --sprite-x: ${number(-e.x/e.width)}; --sprite-y: ${number(-e.y/e.height)};`;
  if (!e.file) css += ` --polygon-x: ${number(e.x/(width-100)*100)}%; --polygon-y: ${number(e.y/(height-100)*100)}%;`;
  css += ' }\n';
}
css += '.sprite-left { transform: rotate(180deg); }\n';
fs.writeFileSync(path.join(root,'assets/css/sprite.css'), css);
fs.writeFileSync(path.join(root,'assets/img/icons/sprite-map.json'), JSON.stringify({width,height,icons:entries.map(({artwork,...e})=>e)},null,2)+'\n');
console.log(`Built ${width} × ${height} sprite: ${icons.length} original PNGs, ${polygons.length} vector polygons.`);
